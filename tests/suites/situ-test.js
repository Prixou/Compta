  const [ch] = await Promise.all([p.waitForEvent('filechooser'), p.click('.fec-drop')]);
  await ch.setFiles(D + 'situ/444444444FEC20261231.txt'); await p.waitForSelector('.fec-meta');
  await p.click('button[data-tab=revue]');
