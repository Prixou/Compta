  await ch2.setFiles(D + 'n1/444444444FEC20251231.txt');
  await p.waitForSelector('.revue-mode button.on:not([disabled])', { timeout: 30000 }); await p.waitForTimeout(500);
  console.log('mode :', (await p.textContent('.revue-mode')).replace(/\s+/g, ' ').trim());
  console.log('KPI projection :', await p.$$eval('section:has(h2:text("Projection")) .kpi', (k) => k.map((x) => x.textContent.replace(/\s+/g, ' ').trim()).join(' | ')));
